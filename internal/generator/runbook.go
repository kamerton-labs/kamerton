func runbook(sd *v1alpha1.SystemDescription, svc *v1alpha1.Service, rs []rulefmt.Rule) string {
	lang := rules.LanguageEnglish
	if n := sd.Spec.Notifications; n != nil && n.Language != "" {
		lang = n.Language
	}
	w, ok := runbookTexts[lang]
	if !ok {
		w = runbookTexts[rules.LanguageEnglish]
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# "+w.title+"\n\n", svc.Name)
	fmt.Fprintf(&b, "> "+w.generated+"\n\n", sd.Name)
	if svc.Description != "" {
		fmt.Fprintf(&b, "%s\n\n", svc.Description)
	}
	fmt.Fprintf(&b, "- %s: %s\n", w.typ, svc.Type)
	critical := w.no
	if svc.Critical {
		critical = w.yes
	}
	fmt.Fprintf(&b, "- %s: %s\n", w.critical, critical)
	if svc.Owner != "" {
		fmt.Fprintf(&b, "- %s: %s\n", w.owner, svc.Owner)
	}
	if len(svc.DependsOn) > 0 {
		fmt.Fprintf(&b, "- %s: %s\n", w.dependsOn, strings.Join(svc.DependsOn, ", "))
	}
	var callers []string
	for _, other := range sd.Spec.Services {
		for _, d := range other.DependsOn {
			if d == svc.Name {
				callers = append(callers, other.Name)
			}
		}
	}
	sort.Strings(callers)
	if len(callers) > 0 {
		fmt.Fprintf(&b, "- %s: %s\n", w.calledBy, strings.Join(callers, ", "))
	}
	fmt.Fprintf(&b, "\n## %s\n\n", w.alerts)
	seen := map[string]bool{}
	for _, r := range rs {
		key := r.Alert + r.Labels[rules.LabelOperation]
		if seen[key] {
			continue
		}
		seen[key] = true
		title := r.Alert
		if op := r.Labels[rules.LabelOperation]; op != "" {
			title += " (" + op + ")"
		}
		fmt.Fprintf(&b, "### %s\n\n", title)
		fmt.Fprintf(&b, "- %s: %s\n- %s: %s\n\n", w.severity, r.Labels[rules.LabelSeverity], w.signal, r.Labels[rules.LabelSignal])
		fmt.Fprintf(&b, "```promql\n%s\n```\n\n", r.Expr)
		if h := w.hints[r.Alert]; h != "" {
			fmt.Fprintf(&b, "%s\n\n", h)
		}
		b.WriteString(w.todo + "\n\n")
	}
	fmt.Fprintf(&b, "## %s\n\n%s\n", w.escalation, w.escalationTodo)
	return b.String()
}

