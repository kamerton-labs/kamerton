/** Russian hint for a field at a schema path (array items as '*'). */
export function hintRu(path: string[]): string | undefined {
  const named = path.filter((p) => p !== '*')
  const field = named[named.length - 1]
  const parent = named[named.length - 2]
  if (!field) return undefined
  return byPath[`${parent}.${field}`] ?? byName[field]
}
